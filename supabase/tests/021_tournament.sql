begin;
create temporary table tournament_results(test text);
grant all on tournament_results to authenticated,anon;
create function pg_temp.denied(label text,statement text) returns void language plpgsql as $$ begin
 begin execute statement; exception when others then insert into tournament_results values(label); return; end;
 raise exception 'Unexpected success: %',label;
end; $$;
grant execute on function pg_temp.denied(text,text) to authenticated,anon;
do $$ declare o uuid; e uuid; s uuid; d uuid; ga uuid; gb uuid; a uuid; b uuid; c uuid; f uuid; u uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); begin
 insert into auth.users(id,email) values(u,'scorer-'||u||'@example.test'),(outsider,'player-'||outsider||'@example.test');
 insert into public.organizations(name,slug) values('Texas tournament test','tournament-'||gen_random_uuid()) returning id into o;
 select id into s from public.sports where lower(name)='cricket' limit 1;
 insert into public.events(organization_id,sport_id,event_name,start_date,end_date,registration_type,status,pricing_model)
 values(o,s,'Austin Cricket Test',current_date+30,current_date+31,'TEAM','REGISTRATION_CLOSED','FREE') returning id into e;
 insert into public.event_staff_assignments(event_id,user_id,staff_role) values(e,u,'SCORER');
 insert into public.teams(event_id,team_name) values(e,'Austin') returning id into a;
 insert into public.teams(event_id,team_name) values(e,'Dallas') returning id into b;
 insert into public.teams(event_id,team_name) values(e,'Houston') returning id into c;
 insert into public.teams(event_id,team_name) values(e,'San Antonio') returning id into f;
 insert into public.divisions(event_id,name) values(e,'Open') returning id into d;
 insert into public.groups(division_id,name) values(d,'Group A') returning id into ga;
 insert into public.groups(division_id,name) values(d,'Group B') returning id into gb;
 insert into public.group_members(group_id,team_id) values(ga,a),(ga,b),(gb,c),(gb,f);
 insert into public.standings(group_id,team_id) values(ga,a),(ga,b),(gb,c),(gb,f);
 insert into public.matches(event_id,division_id,group_id,match_code,stage,home_team_id,away_team_id,status) values
 (e,d,ga,'G1','GROUP',a,b,'READY'),(e,d,gb,'G2','GROUP',c,f,'READY');
 insert into public.matches(event_id,division_id,match_code,stage,status) values(e,d,'SF1','SEMIFINAL','DRAFT'),(e,d,'SF2','SEMIFINAL','DRAFT'),(e,d,'FINAL','FINAL','DRAFT');
 perform set_config('test.te',e::text,true);perform set_config('test.ts',u::text,true);perform set_config('test.to',outsider::text,true);
 perform set_config('test.tm',(select id::text from public.matches where event_id=e and match_code='G1'),true);
end; $$;
select set_config('request.jwt.claim.sub',current_setting('test.ts'),true);
set local role authenticated;
select pg_temp.denied('scorer cannot start tournament',format('select public.tournament_control(%L,''start'')',current_setting('test.te')));
select pg_temp.denied('scoring before tournament start denied',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',current_setting('test.tm')));
reset role;
select set_config('request.jwt.claim.sub','3514e1cc-fca6-478b-a760-cb83eefac27e',true);
set local role authenticated;
select public.tournament_control(current_setting('test.te')::uuid,'start');
insert into tournament_results values('organizer starts tournament with fixtures');
select pg_temp.denied('direct match update denied even to organizer',format('update public.matches set status=''COMPLETED'' where id=%L',current_setting('test.tm')));
select pg_temp.denied('stale schedule denied',format('select public.tournament_control(%L,''schedule'',%L::jsonb)',current_setting('test.te'),jsonb_build_object('match_id',current_setting('test.tm'),'expected_updated_at','2000-01-01','start','2027-07-01T10:00:00Z','end','2027-07-01T11:00:00Z')));
select public.tournament_control(current_setting('test.te')::uuid,'schedule',jsonb_build_object('match_id',current_setting('test.tm'),'expected_updated_at',(select updated_at from public.matches where id=current_setting('test.tm')::uuid),'start','2027-07-01T10:00:00Z','end','2027-07-01T11:00:00Z'));
insert into tournament_results values('organizer schedules a pending match');
select pg_temp.denied('completion before final denied',format('select public.complete_tournament(%L)',current_setting('test.te')));
reset role;
select set_config('request.jwt.claim.sub',current_setting('test.to'),true);
set local role authenticated;
select pg_temp.denied('ordinary player cannot score',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',current_setting('test.tm')));
reset role;
select set_config('request.jwt.claim.sub',current_setting('test.ts'),true);
set local role authenticated;
select pg_temp.denied('null innings denied',format('select public.record_cricket_result(%L,null,4,48,70,8,48)',current_setting('test.tm')));
select pg_temp.denied('invalid wickets denied',format('select public.record_cricket_result(%L,80,11,48,70,8,48)',current_setting('test.tm')));
select pg_temp.denied('balls beyond innings limit denied',format('select public.record_cricket_result(%L,80,4,49,70,8,48)',current_setting('test.tm')));
select pg_temp.denied('scorer cannot resolve semifinals',format('select public.resolve_semifinalists(%L)',current_setting('test.te')));
select public.record_cricket_result(current_setting('test.tm')::uuid,80,4,48,70,8,48);
do $$ begin
 if not exists(select 1 from public.match_results where match_id=current_setting('test.tm')::uuid and verified and verified_by=auth.uid()) then raise exception 'Result audit missing'; end if;
 if not exists(select 1 from public.standings where team_id=(select home_team_id from public.matches where id=current_setting('test.tm')::uuid) and won=1 and played=1) then raise exception 'Standings not recalculated'; end if;
 insert into tournament_results values('scorer confirms result with actor and standings');
end; $$;
select pg_temp.denied('confirmed result cannot be overwritten',format('select public.record_cricket_result(%L,0,4,48,70,8,48)',current_setting('test.tm')));
select public.record_cricket_result((select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='G2'),90,4,48,70,8,48);
reset role;
select set_config('request.jwt.claim.sub','3514e1cc-fca6-478b-a760-cb83eefac27e',true);
set local role authenticated;
select public.resolve_semifinalists(current_setting('test.te')::uuid);
insert into tournament_results values('organizer advances group winners');
select pg_temp.denied('resolved knockout cannot be reset',format('select public.resolve_semifinalists(%L)',current_setting('test.te')));
select pg_temp.denied('schedule enforces team rest conflicts',format('select public.tournament_control(%L,''schedule'',%L::jsonb)',current_setting('test.te'),(select jsonb_build_object('match_id',id,'expected_updated_at',updated_at,'start','2027-07-01T10:30:00Z','end','2027-07-01T11:30:00Z') from public.matches where event_id=current_setting('test.te')::uuid and match_code='SF1')));
reset role;
select set_config('request.jwt.claim.sub',current_setting('test.ts'),true);
set local role authenticated;
select pg_temp.denied('knockout tie denied',format('select public.record_cricket_result(%L,80,4,48,80,8,48)',(select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='SF1')));
select public.record_cricket_result((select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='SF1'),90,4,48,70,8,48);
select public.record_cricket_result((select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='SF2'),100,4,48,70,8,48);
do $$ begin
 if not exists(select 1 from public.matches where event_id=current_setting('test.te')::uuid and match_code='FINAL' and home_team_id is not null and away_team_id is not null) then raise exception 'Final not resolved'; end if;
 insert into tournament_results values('scorer completing semifinals automatically resolves final');
end; $$;
select pg_temp.denied('scorer cannot complete event',format('select public.complete_tournament(%L)',current_setting('test.te')));
reset role;
update public.profiles set account_status='SUSPENDED' where id=current_setting('test.ts')::uuid;
set local role authenticated;
select pg_temp.denied('suspended scorer denied',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',(select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='FINAL')));
reset role;
update public.profiles set account_status='ACTIVE' where id=current_setting('test.ts')::uuid;
update public.event_staff_assignments set status='CANCELLED' where event_id=current_setting('test.te')::uuid;
set local role authenticated;
select pg_temp.denied('revoked scorer denied immediately',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',(select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='FINAL')));
reset role;
update public.event_staff_assignments set status='ASSIGNED' where event_id=current_setting('test.te')::uuid;
set local role authenticated;
select public.record_cricket_result((select id from public.matches where event_id=current_setting('test.te')::uuid and match_code='FINAL'),95,4,48,70,8,48);
reset role;
select set_config('request.jwt.claim.sub','3514e1cc-fca6-478b-a760-cb83eefac27e',true);
set local role authenticated;
select public.complete_tournament(current_setting('test.te')::uuid);
do $$ begin if (select status from public.events where id=current_setting('test.te')::uuid)<>'COMPLETED' then raise exception 'Event not complete'; end if; insert into tournament_results values('organizer completes tournament after confirmed final'); end; $$;
select pg_temp.denied('completed tournament rejects result changes',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',current_setting('test.tm')));
reset role;
set local role anon;
select pg_temp.denied('anonymous score execution denied',format('select public.record_cricket_result(%L,80,4,48,70,8,48)',current_setting('test.tm')));
reset role;
select jsonb_build_object('passed',count(*),'tests',jsonb_agg(test order by test)) as verification from tournament_results;
rollback;
